export function findTariffOffer({ sector, pricingClass, speedMbps } = {}) {
  const speed = Number(speedMbps);
  if (!Number.isFinite(speed)) return null;
  let list = null;
  if (sector === 'private_sector') list = TARIFF_CATALOG.privateSector;
  else if (sector === 'apartment' && pricingClass === 'legacy_existing') list = TARIFF_CATALOG.apartmentExisting;
  else if (sector === 'apartment' && pricingClass === 'new_connection') list = TARIFF_CATALOG.apartmentNewConnection;
  if (!list) return null;
  return list.find(item => item.speedMbps === speed) || null;
}

