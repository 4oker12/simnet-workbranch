  const TYPE_BY_ID = new Map(TYPES.map(item => [item.id, item]));
  const clean = value => String(value == null ? '' : value).replace(/\s+/g, ' ').trim().toLowerCase();

  function type(typeId) {
    return TYPE_BY_ID.get(String(typeId || '')) || null;
  }

  function phrase(typeId, phraseId) {
    return type(typeId)?.phrases?.find(item => item.id === String(phraseId || '')) || null;
  }

  function search(query, limit = 8) {
    const needle = clean(query);
    if (!needle) return [];
    const tokens = needle.split(/[^\p{L}\p{N}]+/u).filter(Boolean);
    const rows = [];
    for (const topic of TYPES) {
      for (const item of topic.phrases) {
        const label = clean(item.label);
        const haystack = [label, ...(item.keywords || []).map(clean), clean(topic.label)].join(' ');
        let score = 0;
        if (label.includes(needle)) score += 20;
        if (haystack.includes(needle)) score += 12;
        for (const token of tokens) {
          if (label.includes(token)) score += 5;
          else if (haystack.includes(token)) score += 2;
        }
        if (score > 0) rows.push({ score, typeId: topic.id, typeLabel: topic.label, phraseId: item.id, label: item.label, icon: item.icon });
      }
    }
    return rows.sort((a,b) => b.score - a.score || a.label.localeCompare(b.label, 'ru')).slice(0, Math.max(1, Number(limit) || 8));
  }

  function forAgent(query) {
    const normalized = clean(query);
    const significant = normalized.split(/[^\p{L}\p{N}]+/u).filter(token => token.length >= 3);
    const hits = significant.length ? search(significant.join(' '), 16) : [];
    const topicIds = [];
    for (const hit of hits) {
      if (!topicIds.includes(hit.typeId)) topicIds.push(hit.typeId);
      if (topicIds.length >= 2) break;
    }

    const scoredCards = OPERATOR_HEURISTICS.map(card => {
      let score = 0;
      const haystack = [card.id, card.split, card.use, ...(card.tags || [])].map(clean).join(' ');
      for (const token of significant) {
        if (haystack.includes(token)) score += token.length >= 5 ? 4 : 2;
      }
      if (/wifi|wi-fi|вай.?фай|ви.?фи/.test(normalized) && ['wifi_band','wifi_distance','wifi_phy','wifi_radio','medium'].includes(card.id)) score += 12;
      if (/скорост/.test(normalized) && ['scope','medium','ethernet_capacity','wifi_band','wifi_distance','wifi_phy','wifi_radio'].includes(card.id)) score += 7;
      if (/нет интернета|не работает интернет/.test(normalized) && ['scope','link_vs_internet','onu_current_state','ip_gateway','dns_path','cpe_reboot','pon_lights'].includes(card.id)) score += 9;
      if (/обрыв|пропад|нестабил/.test(normalized) && ['link_vs_internet','time','stability_events','scope','onu_current_state','recovery','cpe_reboot'].includes(card.id)) score += 9;
      if (/сайт|сервис|dns|vpn|прилож|megogo|netflix/.test(normalized) && ['service_scope','scope','dns_path','vpn_path'].includes(card.id)) score += 9;
      return { card, score };
    }).filter(row => row.score > 0).sort((a,b) => b.score - a.score).slice(0, 8);

    return Object.freeze({
      revision: 'operator-companion-playbook-v5-general-diagnostics',
      mode: topicIds.length ? 'focused' : 'compact-index',
      topicIds: Object.freeze(topicIds),
      suggestedCardIds: Object.freeze(scoredCards.map(row => row.card.id)),
      instruction: 'Master playbook хранится локально; background Context Builder решает, какие карточки реально попадут в prompt.',
      cards: Object.freeze(OPERATOR_HEURISTICS.map(card => Object.freeze({
        id: card.id,
        tags: card.tags,
        split: card.split,
        use: card.use
      })))
    });
  }

